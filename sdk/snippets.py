_CHART_IMPORT = "from analyses._charts import bar_chart, write_chart\n"


_BUCKET_WIDTH = {"year": (4, "YYYY"), "quarter": (7, "YYYY-MM, map to quarter"),
                 "month": (7, "YYYY-MM"), "day": (10, "YYYY-MM-DD")}


def _unit_note(profile: Profile, match: Match) -> str:
    if match.unit == "entity":
        return "Rows are collapsed per entity before anything is counted."
    if not profile.has_dedupe_key:
        return ("This archetype has no entity key, so results describe {0}s "
                "and not entities. Report that denominator.".format(profile.grain.label))
    return "Report this denominator in your methods."


def _caveat_block(match: Match) -> str:
    if not match.warnings:
        return ""
    lines = ["", "Measured warnings that apply to this analysis:"]
    for warning in match.warnings:
        lines.append("  - " + warning)
    lines.append("")
    return "\n".join(lines)


# How far to truncate a timestamp for each releasable bucket.
_BUCKET_CHARS = {"year": 4, "quarter": 7, "month": 7, "day": 10}


def _describe_body(profile: Profile) -> str:
    """Emit one accumulation line per leaf, at the resolution it may be released.

    An aggregate-only field is coarsened here rather than reported raw: a
    HIGH_LEVEL timestamp releasable as a month must never leave the function as
    a timestamp, and a template that emits one is not enforcing the policy it
    claims to.
    """
    lines = []
    for leaf in profile.all_leaves():
        expr = accessor(leaf.path)
        if leaf.is_numeric:
            lines.append('        numeric["{0}"].append(_number({1}))'.format(
                leaf.path, expr))
        elif leaf.is_temporal and not leaf.is_detailed:
            bucket = (leaf.releasable_as or ["year"])[-1]
            width = _BUCKET_CHARS.get(bucket, 4)
            lines.append(
                '        totals["{0}"][_bucket({1}, {2})] += 1'
                '  # {3}, per the profile'.format(leaf.path, expr, width, bucket))
        else:
            lines.append('        totals["{0}"][str({1})] += 1'.format(
                leaf.path, expr))
    lines.append("")
    return "\n".join(lines)


def _logistic_body(covariates: List[str]) -> str:
    lines = []
    for path in covariates:
        lines.append('        strata[("{0}", str({1}))][outcome] += 1'.format(path, accessor(path)))
    lines.append("")
    return "\n".join(lines)


_NUMBER_HELPER = '''
def _number(value):
    """Coerce a CSV field to a number, or None when it is not one."""
    try:
        return float(value)
    except (TypeError, ValueError):
        return None

'''


def render(profile: Profile, match: Match, chart: bool = False) -> str:
    """Render the analysis code for a feasible match.

    With chart=True the module also gains a chart() that draws the *released*
    result -- the same suppressed aggregate main() returns. A figure drawn from
    records rather than from the released table is a disclosure risk that no
    output review can see, so the generator never offers that shape.
    """
    if not match.feasible:
        raise SnippetError(
            "{0} is not feasible for this dataset: {1}".format(
                match.key, match.blockers[0] if match.blockers else "unknown reason"))
    template = _TEMPLATES.get(match.key)
    if template is None:
        raise SnippetError("no template for analysis '{0}'".format(match.key))

    card_ref = profile.schema_hash[:12] if profile.schema_hash else (profile.archetype_id or "measured locally")
    values = {
        "title": match.title,
        "summary": match.summary,
        "unit": match.unit,
        "unit_note": _unit_note(profile, match),
        "caveat_block": _caveat_block(match),
        "card_ref": card_ref,
        "min_cell": str(profile.min_cell),
    }

    body = _HEADER
    params = match.params

    if match.key == "describe":
        body += _NUMBER_HELPER + _SUPPRESS
        values["describe_body"] = _describe_body(profile)
    elif match.key == "composition":
        values["outcome_expr"] = accessor(params["outcome"])
        values["by_expr"] = accessor(params["by"])
        values["outcome_name"] = _slug(params["outcome"])
        values["by_name"] = _slug(params["by"])
    elif match.key == "cross_tab":
        values["rows_expr"] = accessor(params["rows"])
        values["cols_expr"] = accessor(params["cols"])
        values["rows_name"] = _slug(params["rows"])
        values["cols_name"] = _slug(params["cols"])
    elif match.key == "prevalence":
        if not profile.grain.dedupe_key:
            raise SnippetError("prevalence requires a dedupe key")
        body = body.replace("MIN_CELL = $min_cell", 'POSITIVE = set()  # fill in the values that count as positive\nMIN_CELL = $min_cell')
        values["dedupe_expr"] = accessor(profile.grain.dedupe_key)
        values["outcome_expr"] = accessor(params["outcome"])
    elif match.key == "group_compare":
        values["value_expr"] = accessor(params["value"])
        values["group_expr"] = accessor(params["group"])
    elif match.key == "logistic":
        body = body.replace("MIN_CELL = $min_cell", 'POSITIVE = set()  # fill in the values that count as positive\nMIN_CELL = $min_cell')
        covariates = [c.strip() for c in params.get("covariates", "").split(",") if c.strip()]
        values["outcome_expr"] = accessor(params["outcome"])
        values["outcome_name"] = params["outcome"]
        values["logistic_body"] = _logistic_body(covariates)
    elif match.key == "trend":
        bucket = (params.get("buckets") or "year").split(",")[0].strip()
        width, note = _BUCKET_WIDTH.get(bucket, _BUCKET_WIDTH["year"])
        values["time_expr"] = accessor(params["time"])
        values["bucket_width"] = str(width)
        values["bucket_note"] = note
        values["bucket_label"] = bucket

    section = _CHART_SECTIONS.get(match.key) if chart else None
    if chart and section is None:
        raise SnippetError(
            "'{0}' has no chart: it returns a single figure rather than a "
            "table. Chartable analyses: {1}.".format(
                match.key, ", ".join(sorted(_CHART_SECTIONS))))
    if section:
        body = body.replace("from generated.models import create_dataset",
                            "from generated.models import create_dataset\n"
                            + _CHART_IMPORT.rstrip())
        template = template.replace(
            '''if __name__ == "__main__":''',
            section.strip() + '''\n\nif __name__ == "__main__":''')
        template = template.replace(
            "print(json.dumps(main(), indent=2, default=str))",
            "print(json.dumps(main(), indent=2, default=str))\n"
            "    print(\"chart written to\", chart())")
        values["chart_path"] = "{0}.svg".format(match.key)
        values["chart_title"] = _chart_title(match)

    return Template(body + template).safe_substitute(values)


def _chart_title(match: Match) -> str:
    params = match.params
    if match.key == "cross_tab":
        return "{0} by {1}".format(params.get("rows", ""), params.get("cols", ""))
    if match.key == "composition":
        return "{0} by {1}".format(params.get("outcome", ""), params.get("by", ""))
    return match.title


def write(profile: Profile, match: Match, project_dir: str = ".",
          filename: Optional[str] = None, chart: bool = False) -> str:
    """Render a snippet and write it under analyses/. Returns the path."""
    code = render(profile, match, chart=chart)
    directory = os.path.join(project_dir, ANALYSES_DIR)
    if not os.path.isdir(directory):
        os.makedirs(directory)
    init_path = os.path.join(directory, "__init__.py")
    if not os.path.exists(init_path):
        with open(init_path, "w", encoding="utf-8") as fh:
            fh.write("")
    # Snippets always land directly in analyses/. Callers -- an agent among
    # them -- routinely pass "analyses/foo.py", which would otherwise nest a
    # second analyses/ and fail on the missing directory.
    name = os.path.basename(filename or "{0}.py".format(match.key))
    if not name:
        raise SnippetError("filename is empty")
    if not name.endswith(".py"):
        name += ".py"
    if chart:
        helper = os.path.join(directory, CHART_HELPER_NAME)
        if not os.path.exists(helper):
            with open(helper, "w", encoding="utf-8") as fh:
                fh.write(CHART_MODULE)

    path = os.path.join(directory, name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(code)
    return path
