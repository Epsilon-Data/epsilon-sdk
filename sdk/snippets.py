# Written to analyses/_charts.py the first time a chart snippet is generated.
# Stdlib only and deliberately so: the enclave's requirements carry no plotting
# library, and an SVG is text a reviewer can read, unlike a PNG.
CHART_MODULE = '''"""Minimal SVG charts for disclosure-safe output.

Charts are output artifacts. These render from an already-suppressed aggregate
-- a value of None means the cell was below the threshold and is drawn as a
suppressed marker, never as a height. Nothing here touches a record.

Generated by epsilon copilot. Stdlib only; safe to edit.
"""

BAR_HEIGHT = 22
BAR_GAP = 8
LEFT = 190
RIGHT = 70
TOP = 44
PAD = 16

# Chosen to stay legible on a white or a dark background.
INK = "#2b3a36"
MUTED = "#7c8c87"
ACCENT = "#0d6b60"
SUPPRESSED = "#c2cdc9"


def _escape(text):
    return (str(text).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def bar_chart(title, rows, width=720, note=None):
    """Render (label, value) pairs as a horizontal bar chart.

    `value` may be None, meaning the count was suppressed; such rows are drawn
    as a marker with no length so a suppressed cell can never be read back off
    the axis.
    """
    rows = list(rows)
    if not rows:
        return _empty(title, width, "no rows to plot")

    shown = [v for _label, v in rows if v is not None]
    top = max(shown) if shown else 0
    plot = max(width - LEFT - RIGHT, 60)
    height = TOP + len(rows) * (BAR_HEIGHT + BAR_GAP) + PAD + (20 if note else 0)

    out = [
        \'<svg xmlns="http://www.w3.org/2000/svg" width="{0}" height="{1}" \'
        \'viewBox="0 0 {0} {1}" font-family="ui-sans-serif, system-ui, sans-serif">\'
        .format(width, height),
        \'<text x="{0}" y="24" font-size="14" font-weight="600" fill="{1}">{2}</text>\'
        .format(PAD, INK, _escape(title)),
    ]

    y = TOP
    for label, value in rows:
        out.append(
            \'<text x="{0}" y="{1}" font-size="12" fill="{2}" \'
            \'text-anchor="end">{3}</text>\'.format(
                LEFT - 10, y + BAR_HEIGHT - 6, MUTED, _escape(label)[:32]))
        if value is None:
            out.append(
                \'<rect x="{0}" y="{1}" width="26" height="{2}" rx="2" \'
                \'fill="{3}"/>\'.format(LEFT, y, BAR_HEIGHT, SUPPRESSED))
            out.append(
                \'<text x="{0}" y="{1}" font-size="11" fill="{2}">suppressed</text>\'
                .format(LEFT + 34, y + BAR_HEIGHT - 6, MUTED))
        else:
            length = int(plot * (float(value) / top)) if top else 0
            out.append(
                \'<rect x="{0}" y="{1}" width="{2}" height="{3}" rx="2" \'
                \'fill="{4}"/>\'.format(LEFT, y, max(length, 1), BAR_HEIGHT, ACCENT))
            out.append(
                \'<text x="{0}" y="{1}" font-size="11" fill="{2}">{3:,}</text>\'
                .format(LEFT + length + 8, y + BAR_HEIGHT - 6, INK, value))
        y += BAR_HEIGHT + BAR_GAP

    if note:
        out.append(
            \'<text x="{0}" y="{1}" font-size="11" fill="{2}">{3}</text>\'
            .format(PAD, height - 8, MUTED, _escape(note)))
    out.append("</svg>")
    return "\\n".join(out)


def _empty(title, width, message):
    return (\'<svg xmlns="http://www.w3.org/2000/svg" width="{0}" height="80">\'
            \'<text x="16" y="30" font-size="14">{1}</text>\'
            \'<text x="16" y="54" font-size="12" fill="{2}">{3}</text></svg>\'
            ).format(width, _escape(title), MUTED, _escape(message))


def write_chart(path, svg):
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(svg)
    return path
'''


